// Copies the runtime part of src/aleph/prompts/parse_query.md (between the
// prompt:start / prompt:end markers) into worker/prompt.generated.ts, so the
// Worker sends exactly the prompt the repository versions. Run before build.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(here, '../../src/aleph/prompts/parse_query.md')
const out = resolve(here, '../worker/prompt.generated.ts')

if (!existsSync(src)) {
  if (existsSync(out)) {
    console.log('sync-prompt: source not found, keeping the committed prompt.generated.ts')
    process.exit(0)
  }
  console.error(`sync-prompt: ${src} not found and no generated file exists`)
  process.exit(1)
}

const md = readFileSync(src, 'utf8')
const m = md.match(/<!-- prompt:start -->([\s\S]*?)<!-- prompt:end -->/)
if (!m) {
  console.error('sync-prompt: prompt markers not found')
  process.exit(1)
}
const version = md.match(/`prompt_version`\s*\|\s*(\d+)/)?.[1] ?? 'unknown'
const body = m[1].trim()
writeFileSync(
  out,
  `// Generated by scripts/sync-prompt.mjs from src/aleph/prompts/parse_query.md. Do not edit.\nexport const PROMPT_VERSION = ${JSON.stringify(version)}\nexport const PARSE_PROMPT = ${JSON.stringify(body)}\n`,
)
console.log(`sync-prompt: wrote prompt v${version} (${body.length} chars)`)
